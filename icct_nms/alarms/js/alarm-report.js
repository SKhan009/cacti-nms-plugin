(() => {
    'use strict';
    const blank = (value) => value === null || value === undefined || String(value).trim() === '' ? '—' : String(value);
    const stamp = (epoch) => {
        if (!Number(epoch)) return '—';
        const p = Object.fromEntries(new Intl.DateTimeFormat('en-GB', {
            timeZone: 'Asia/Kolkata', day: '2-digit', month: '2-digit', year: 'numeric',
            hour: '2-digit', minute: '2-digit', second: '2-digit', hourCycle: 'h23',
        }).formatToParts(new Date(Number(epoch) * 1000)).map((part) => [part.type, part.value]));
        return `${p.day}-${p.month}-${p.year} ${p.hour}:${p.minute}:${p.second}`;
    };
    const status = (flag, yes, no) => Number(flag) ? yes : no;
    const cell = (text, extra = {}) => ({ text: blank(text), ...extra });
    const small = (text, extra = {}) => cell(text, { fontSize: 8, ...extra });
    const reportValue = (value) => value === null || value === undefined || String(value).trim() === '' ? '-' : String(value);
    const reportFilename = (device) => {
        const safe = String(device || 'All Devices')
            .replace(/[\\/:*?"<>|\x00-\x1f]/g, '-')
            .replace(/\s+/g, ' ')
            .replace(/[.\s-]+$/g, '')
            .trim()
            .slice(0, 100);
        return `${safe || 'All Devices'} - Alarm Report.pdf`;
    };
    const reportDuration = (values) => {
        const epochs = values.map(Number).filter((value) => Number.isFinite(value) && value > 0);
        return epochs.length
            ? `Report Duration: ${stamp(Math.min(...epochs))} – ${stamp(Math.max(...epochs))}`
            : 'Report Duration: —';
    };
    const primarySecondary = (primary, secondary) => ({ stack: [
        { text: reportValue(primary), bold: true, fontSize: 8, margin: [0, 0, 0, 3] },
        { text: reportValue(secondary), fontSize: 8, color: '#333333' },
    ] });
    const gray = '#f2f2f2';
    const border = '#c9c9c9';
    const layout = {
        hLineColor: () => border, vLineColor: () => border,
        hLineWidth: () => 0.45, vLineWidth: () => 0.45,
        paddingLeft: () => 5, paddingRight: () => 5,
        paddingTop: () => 6, paddingBottom: () => 6,
    };
    const labelValue = (label, value) => [small(label, { bold: true, fillColor: gray }), small(value, { fillColor: gray })];
    let logoPromise;
    function logo() {
        if (!logoPromise) logoPromise = fetch('shared/assets/images/drdo-logo-report.png')
            .then((response) => {
                if (!response.ok) throw new Error('Report logo is unavailable.');
                return response.blob();
            }).then((blob) => new Promise((resolve, reject) => {
                const reader = new FileReader();
                reader.onload = () => resolve(reader.result);
                reader.onerror = () => reject(new Error('Report logo could not be loaded.'));
                reader.readAsDataURL(blob);
            }));
        return logoPromise;
    }
    function base(meta, image, title, duration = '') {
        return {
            pageSize: 'A4', pageOrientation: 'landscape', pageMargins: [38, 100, 38, 44],
            defaultStyle: { font: 'Roboto', fontSize: 8, color: '#171717' },
            header: () => ({ margin: [38, 25, 38, 0], stack: [
                { columns: [
                    { width: 31, image, fit: [26, 26] },
                    { width: '*', stack: [
                        { text: blank(meta.site), bold: true, fontSize: 12, margin: [0, 0, 0, 2] },
                        { text: 'ICCT NMS', color: '#666666', fontSize: 8 },
                    ] },
                    { width: 275, stack: [
                        { text: title, bold: true, fontSize: 13, alignment: 'right' },
                        { text: duration, color: '#666666', fontSize: 8, alignment: 'right', margin: [0, 3, 0, 0] },
                    ] },
                ] },
                { columns: [
                    { text: [{ text: 'Generated At:  ', bold: true }, stamp(Date.now() / 1000)] },
                    { text: [{ text: 'Generated By:  ', bold: true }, blank(meta.user)], alignment: 'right' },
                ], fontSize: 8, margin: [0, 12, 0, 5] },
                { canvas: [{ type: 'line', x1: 0, y1: 0, x2: 766, y2: 0, lineWidth: 0.5, lineColor: border }] },
            ] }),
            footer: (page, pages) => ({ margin: [38, 8, 38, 0], columns: [
                { text: 'Generated by Cacti System', width: '*' },
                { text: 'Confidential – For Authorized Use Only', width: '*', alignment: 'center' },
                { text: `Page ${page} of ${pages}`, width: '*', alignment: 'right' },
            ], fontSize: 7, color: '#333333' }),
            info: { title, author: blank(meta.user), subject: 'ICCT NMS alarm report' },
        };
    }
    function table(headers, widths, rows) {
        return { table: {
            headerRows: 1, widths, dontBreakRows: true,
            body: [headers.map((h) => cell(h, { bold: true, fillColor: '#dddddd', fontSize: 7.5 })), ...rows],
        }, layout, margin: [0, 0, 0, 8] };
    }
    function note(value) { return blank(value); }
    function description(alarm) {
        return [blank(alarm.description), alarm.fix ? `Fix: ${alarm.fix}` : ''].filter(Boolean).join('\n');
    }
    async function list(rows, meta) {
        if (!window.pdfMake) throw new Error('PDF generator is unavailable.');
        const image = await logo();
        const doc = base(meta, image, 'ALARM REPORT', reportDuration(rows.map((r) => r.occurred_epoch)));
        doc.content = [table(
            ['S.No', 'Alarm Occurred', 'Severity', 'Device Name & Short Name', 'IP Address & Type of Network Element', 'Alarm Name (Count)', 'Alarm Description & Fix', 'Ack & Remarks'],
            [35, 60, 51, 77, 85, 83, '*', 145],
            rows.map((r, index) => [
                small(`${index + 1}.`), small(stamp(r.occurred_epoch)),
                small(reportValue(r.severity).toUpperCase(), { bold: true }),
                primarySecondary(r.device_name, r.short_name),
                primarySecondary(r.address, r.network_type),
                small(`${reportValue(r.name)} (${Number(r.occurrences) || 0})`, { bold: true }),
                primarySecondary(r.description, r.fix),
                primarySecondary(status(r.acknowledged, 'Ack', 'Not_Ack'), r.ack_note),
            ]),
        )];
        if (!rows.length) doc.content.push({ text: 'No alarms match the selected filters.', margin: [0, 12, 0, 0] });
        const devices = [...new Set(rows.map((r) => String(r.device_name || '').trim()).filter(Boolean))];
        const device = devices.length === 1 ? devices[0] : devices.length === 0 ? meta.selectedDevice : 'All Devices';
        window.pdfMake.createPdf(doc).download(reportFilename(device));
    }
    function section(text) { return { text, bold: true, fontSize: 10, margin: [0, 8, 0, 9] }; }
    function pairRows(pairs) {
        return { table: { widths: ['50%', '50%'], body: pairs.map(([name, value]) => labelValue(name, value)) },
            layout: { ...layout, hLineWidth: () => 0, vLineWidth: () => 0, paddingTop: () => 5, paddingBottom: () => 5 } };
    }
    async function detail(data, meta) {
        if (!window.pdfMake) throw new Error('PDF generator is unavailable.');
        const image = await logo();
        const r = data.alarm;
        const duration = reportDuration([
            r.occurred_epoch,
            r.observed_epoch,
            ...(data.occurrence_history || []).map((event) => event.created_epoch),
            ...(data.ticket?.timeline || []).map((event) => event.created_epoch),
        ]);
        const doc = base(meta, image, 'ALARM REPORT', duration);
        const ack = data.acknowledgement;
        const actor = ack ? (ack.actor_username || ack.actor_name || (ack.actor_id ? `User ${ack.actor_id}` : 'Automatic')) +
            (ack.actor_email ? ` (${ack.actor_email})` : '') : '—';
        doc.content = [
            section('Alarm Details'),
            pairRows([
                ['Alarm Occurred', stamp(r.occurred_epoch)],
                ['Device Name', r.device_name],
                ['Short Name', r.short_name],
                ['IP Address', r.address],
                ['Type of Network Element', r.network_type],
                ['Alarm Name & Count', `${blank(r.name)} (${Number(r.occurrences) || 0})`],
                ['Ack Status', status(r.acknowledged, 'Ack', 'Not_Ack')],
                ['Escalation Status', status(r.escalated, 'Esc', 'Not_Esc')],
            ]),
            section('Description & Fix'),
            { text: description(r), margin: [0, 0, 0, 12] },
            section('Acknowledgement & Remarks'),
            pairRows([['Remarks', ack?.note], ['Acknowledged By', actor]]),
        ];
        const occurrences = data.occurrence_history || [];
        if (occurrences.length) {
            doc.content.push({ ...section('Alarm History'), pageBreak: 'before' });
            doc.content.push(table(
                ['S.No', 'Alarm Occurred', 'Severity', 'Alarm Description & Fix', 'Ack & Remarks', 'Count'],
                [28, 90, 67, '*', 154, 42],
                occurrences.map((e, index) => {
                    const s = e.snapshot || {};
                    return [small(`${index + 1}.`), small(stamp(e.created_epoch)), small(s.severity || r.severity, { bold: true }),
                        small(description({ description: s.description || r.description, fix: s.fix || r.fix })),
                        small(`${s.acknowledged === undefined ? '—' : status(s.acknowledged, 'Ack', 'Not_Ack')}\n${e.event === 'Acknowledged' ? note(e.note) : note(s.ack_note)}`),
                        small(s.occurrences ?? '—')];
                }),
            ));
        }
        if (data.ticket?.details) {
            const ticket = data.ticket;
            doc.content.push({ ...section('Escalation'), pageBreak: 'before' });
            doc.content.push(pairRows([
                ['Ticket Severity', ticket.details.severity],
                ['Ticket Name', ticket.details.name],
                ['Remarks', ticket.details.remarks],
            ]));
            doc.content.push(section('Escalation Progress'));
            for (const event of ticket.timeline || []) {
                const color = { resolved: '#e5a000', progress: '#15a58c', reopen: '#ef6b23', opened: '#2364dc', closed: '#238c4d' }[event.kind] || '#888888';
                doc.content.push({ table: { widths: [1.5, '*'], body: [[
                    { text: ' ', fillColor: color },
                    { stack: [
                        cell(event.label, { bold: true }),
                        small(stamp(event.created_epoch), { color: '#666666' }),
                        small(event.note, { color: '#666666' }),
                    ] },
                ]] }, layout: {
                    hLineWidth: () => 0, vLineWidth: () => 0,
                    paddingLeft: (column) => column === 0 ? 0 : 8,
                    paddingRight: () => 0,
                    paddingTop: () => 0, paddingBottom: () => 0,
                }, margin: [0, 0, 0, 7] });
            }
        }
        window.pdfMake.createPdf(doc).download(reportFilename(r.device_name));
    }
    window.icctAlarmPdf = { list, detail };
})();
